import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Module} from 'node:module';
import {createHash} from 'node:crypto';
import ts from 'typescript';
import {readCatalog,catalogSourceBytes} from './catalog-source.mjs';
const meta=JSON.parse(readFileSync(new URL('../data/catalog-meta.json',import.meta.url)));
const expected=readCatalog(),source=catalogSourceBytes(expected);
const index=JSON.parse(readFileSync(new URL('../data/catalog-index.json',import.meta.url)));
assert.equal(index.version,meta.version);
assert.equal(Object.keys(index.byId).length,expected.length);
for(let n=0;n<expected.length;n++)assert.equal(index.byId[expected[n].id],Math.floor(n/1000),'the server index points to the exact source part');
assert.equal(meta.version,createHash('sha256').update(source).digest('hex'),'delivery must match the exact published catalog');
const mod=new Module(process.cwd()+'/lib/catalog-loader.cjs');
mod._compile(ts.transpileModule(readFileSync(new URL('../lib/catalog-loader.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,'catalog-loader.cjs');
const {loadCatalog}=mod.exports;
let active=0,maximum=0;const progress=[];
const fetcher=async(path,options)=>{
 if(options.signal.aborted)throw new Error('aborted');
 active++;maximum=Math.max(maximum,active);await Promise.resolve();
 const text=readFileSync(new URL('../public'+path,import.meta.url),'utf8');active--;
 return {ok:true,json:async()=>JSON.parse(text)};
};
const received=await loadCatalog(meta,fetcher,new AbortController().signal,n=>progress.push(n));
assert.deepEqual(received,expected,'all original fields and record order must survive chunked delivery');
assert.equal(progress.at(-1),expected.length);assert(maximum<=3,'parallel requests stay bounded');
await assert.rejects(loadCatalog(meta,async()=>({ok:false}),new AbortController().signal,()=>{}),/暂未读取成功/);
await assert.rejects(loadCatalog(meta,async()=>({ok:true,json:async()=>({version:'other',part:0,records:[]})}),new AbortController().signal,()=>{}),/版本不一致/);
const cancel=new AbortController();cancel.abort();
await assert.rejects(loadCatalog(meta,fetcher,cancel.signal,()=>{}),/aborted/);
console.log(`检查通过：${received.length} 条岗位分批读取无字段损失；版本、读取失败、取消及并发边界正常。`);
